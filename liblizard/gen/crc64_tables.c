// Writes src/crc64_tables.h: the block CRC's slicing-by-8 tables (src/layout.c ob_crc64). The CRC's generator is
// G = (x + 1) m1 m3 m5 m7 m9 (x^3 + x + 1), the m's the minimal polynomials of alpha^1, 3, 5, 7, 9 over GF(2^12)
// (alpha a root of x^12 + x^6 + x^4 + x + 1): 0xE0CB4CBE2D1C3403 with x^64, reflected 0xC02C38B47D32D307; the register
// set to all ones, the result inverted; "123456789" gives 0xBB3BA0D234061B3E. Its roots alpha^0 .. alpha^10 make it a
// BCH code of length 4,095 with distance at least 12 (its roots checked in the lab, crc64-poly-2026-11-21). T[0][b] is
// byte b's CRC from a zero register (eight reflected steps); T[k][b] = T[k - 1][b] >> 8 ^ T[0][T[k - 1][b] & 0xff], byte
// b followed by k zero bytes.
// Run from liblizard/: cc -O2 -o build/crc64_tables gen/crc64_tables.c && build/crc64_tables
#include <stdint.h>
#include <stdio.h>

int main(void) {
  const uint64_t P = 0xc02c38b47d32d307ull;
  static uint64_t T[8][256];
  for (int b = 0; b < 256; b++) {
    uint64_t c = (uint64_t)b;
    for (int i = 0; i < 8; i++) c = (c >> 1) ^ ((c & 1) ? P : 0);
    T[0][b] = c;
  }
  for (int k = 1; k < 8; k++)
    for (int b = 0; b < 256; b++) T[k][b] = (T[k - 1][b] >> 8) ^ T[0][T[k - 1][b] & 0xff];
  uint64_t check = ~0ull;
  for (const char* x = "123456789"; *x; x++) check = (check >> 8) ^ T[0][(check ^ (uint8_t)*x) & 0xff];
  check = ~check;
  if (check != 0xbb3ba0d234061b3eull) { fprintf(stderr, "the block CRC's check value %016llx\n", (unsigned long long)check); return 1; }
  FILE* f = fopen("src/crc64_tables.h.part", "w");
  if (!f) { perror("src/crc64_tables.h.part"); return 1; }
  fputs("// The block CRC's slicing-by-8 tables (layout.c ob_crc64): the BCH-derived CRC-64, reflected 0xC02C38B47D32D307. T[0][b] is\n"
        "// byte b's CRC from a zero register, T[k][b] byte b followed by k zero bytes. Generated by gen/crc64_tables.c; do not\n"
        "// edit.\n#ifndef CRC64_TABLES_H\n#define CRC64_TABLES_H\n#include <stdint.h>\n\nstatic const uint64_t CRC64_T[8][256] = {\n", f);
  for (int k = 0; k < 8; k++) {
    fputs("  {\n", f);
    for (int r = 0; r < 64; r++)
      fprintf(f, "    0x%016llxull, 0x%016llxull, 0x%016llxull, 0x%016llxull,\n", (unsigned long long)T[k][4 * r], (unsigned long long)T[k][4 * r + 1],
              (unsigned long long)T[k][4 * r + 2], (unsigned long long)T[k][4 * r + 3]);
    fputs("  },\n", f);
  }
  fputs("};\n\n#endif\n", f);
  if (fclose(f) != 0 || rename("src/crc64_tables.h.part", "src/crc64_tables.h") != 0) { perror("src/crc64_tables.h"); return 1; }
  printf("crc64_tables.h written; check %016llx\n", (unsigned long long)check);
  return 0;
}
