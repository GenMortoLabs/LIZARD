// Writes ../src/crc64_tables.h: the block CRC's slicing-by-8 tables (src/layout.c ob_crc64). The CRC's generator is
// G = (x + 1) m1 m3 m5 m7 m9 (x^3 + x + 1), the m's the minimal polynomials of alpha^1, 3, 5, 7, 9 over GF(2^12)
// (alpha a root of x^12 + x^6 + x^4 + x + 1): 0xE0CB4CBE2D1C3403 with x^64, reflected 0xC02C38B47D32D307; the register
// set to all ones, the result inverted; "123456789" gives 0xBB3BA0D234061B3E. Its roots alpha^0 .. alpha^10 make it a
// BCH code of length 4,095 with distance at least 12 (its roots checked in the lab, crc64-poly-2026-11-21). T[0][b] is
// byte b's CRC from a zero register (eight reflected steps); T[k][b] = T[k - 1][b] >> 8 ^ T[0][T[k - 1][b] & 0xff], byte b followed by k zero bytes.
// Run from the root: node liblizard/gen/crc64_tables.mjs
import { writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";

const P = 0xc02c38b47d32d307n, M = (1n << 64n) - 1n;
const T = Array.from({ length: 8 }, () => new Array(256));
for (let b = 0; b < 256; b++) {
  let c = BigInt(b);
  for (let i = 0; i < 8; i++) c = (c >> 1n) ^ (c & 1n ? P : 0n);
  T[0][b] = c;
}
for (let k = 1; k < 8; k++) for (let b = 0; b < 256; b++) T[k][b] = (T[k - 1][b] >> 8n) ^ T[0][Number(T[k - 1][b] & 0xffn)];
let check = M;
for (const x of Buffer.from("123456789")) check = (check >> 8n) ^ T[0][Number((check ^ BigInt(x)) & 0xffn)];
check ^= M;
if (check !== 0xbb3ba0d234061b3en) throw new Error(`the block CRC's check value ${check.toString(16)}`);
const hex = (v) => `0x${v.toString(16).padStart(16, "0")}ull`;
const rows = T.map((t) => `  {\n${Array.from({ length: 64 }, (_, r) => `    ${t.slice(4 * r, 4 * r + 4).map(hex).join(", ")},`).join("\n")}\n  },`).join("\n");
const out = `// The block CRC's slicing-by-8 tables (layout.c ob_crc64): the BCH-derived CRC-64, reflected 0xC02C38B47D32D307. T[0][b] is
// byte b's CRC from a zero register, T[k][b] byte b followed by k zero bytes. Generated by gen/crc64_tables.mjs; do not
// edit.
#ifndef CRC64_TABLES_H
#define CRC64_TABLES_H
#include <stdint.h>

static const uint64_t CRC64_T[8][256] = {
${rows}
};

#endif
`;
writeFileSync(fileURLToPath(new URL("../src/crc64_tables.h", import.meta.url)), out);
console.log(`crc64_tables.h written; check ${check.toString(16)}`);
