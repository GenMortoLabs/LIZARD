// Writes src/fmt_tables.h: the tables the format word's index takes its layouts by (src/fmt.c ob_fmt_index,
// ob_fmt_config). Every block size is a whole number of OB_FMT_UNIT (640) data slots (each code's sent bits, ldpc.c
// ldpc_sent_bits: the 6/7 code's 7, the 3/4's 8, the 2/3's 9 and the 1/2's 12), so a layout of a 6/7, b 3/4, t 2/3 and
// c 1/2 blocks fits version v when 7a + 8b + 9t + 12c <= R(v) = floor(OB_FMT_SLOTS v / OB_FMT_UNIT), at most 1065
// (version 67). P2[r] is the number of (t, c) with 9t + 12c <= r, P3[r] the number of (b, t, c) with 8b + 9t + 12c <= r,
// BEFORE[v - 1] the layouts of every version before v (sum over a of P3[R - 7a]), the last OB_FMT_CONFIGS.
// Run from liblizard/: cc -O2 -Isrc -o build/fmt_tables gen/fmt_tables.c src/fmt.c src/rs.c src/layout.c src/ldpc.c -lm &&
// build/fmt_tables
#include <stdint.h>
#include <stdio.h>

#include "fmt.h"
#include "ldpc.h"

#define VMAX OB_FMT_VERSION_MAX
static int R(int v) { return OB_FMT_SLOTS * v / OB_FMT_UNIT; }

static void rows(FILE* f, const long* a, int n, int per) {
  for (int i = 0; i < n; i += per) {
    fputs("  ", f);
    for (int k = i; k < n && k < i + per; k++) fprintf(f, "%ld%s", a[k], k + 1 < n && k + 1 < i + per ? ", " : ",");
    fputs("\n", f);
  }
}

int main(void) {
  int u[OB_TIERS];
  for (int i = 0; i < OB_TIERS; i++) {
    const int s = ldpc_sent_bits(OB_TIER_RATE[i]);
    if (s % OB_FMT_UNIT) { fprintf(stderr, "a block of %d slots is no whole number of %d\n", s, OB_FMT_UNIT); return 1; }
    u[i] = s / OB_FMT_UNIT;
  }
  const int RMAX = R(VMAX);
  static long P2[4096], P3[4096], BEFORE[VMAX + 1];
  if (RMAX >= 4096) { fprintf(stderr, "room %d past the tables\n", RMAX); return 1; }
  long p2max = 0;
  for (int r = 0; r <= RMAX; r++) {
    long n = 0;
    for (int t = 0; u[2] * t <= r; t++) n += (r - u[2] * t) / u[3] + 1;
    P2[r] = n;
    if (n > p2max) p2max = n;
  }
  for (int r = 0; r <= RMAX; r++) {
    long n = 0;
    for (int b = 0; u[1] * b <= r; b++) n += P2[r - u[1] * b];
    P3[r] = n;
  }
  BEFORE[0] = 0;
  for (int v = 1; v <= VMAX; v++) {
    long n = 0;
    for (int a = 0; u[0] * a <= R(v); a++) n += P3[R(v) - u[0] * a];
    BEFORE[v] = BEFORE[v - 1] + n;
  }
  if (BEFORE[VMAX] != OB_FMT_CONFIGS) { fprintf(stderr, "the layouts' count %ld, not OB_FMT_CONFIGS\n", BEFORE[VMAX]); return 1; }
  if (p2max > 65535) { fprintf(stderr, "P2 past 16 bits\n"); return 1; }
  FILE* f = fopen("src/fmt_tables.h.part", "w");
  if (!f) { perror("src/fmt_tables.h.part"); return 1; }
  fprintf(f, "// The format word's layout tables (fmt.c ob_fmt_index, ob_fmt_config): in units of OB_FMT_UNIT (640) data slots, the\n"
             "// 6/7, 3/4, 2/3 and 1/2 blocks %d, %d, %d and %d units. FMT_P2[r]: the (t, c) with %dt + %dc <= r; FMT_P3[r]: the (b, t, c)\n"
             "// with %db + %dt + %dc <= r; FMT_BEFORE[v - 1]: the layouts of every version before v, the last OB_FMT_CONFIGS.\n"
             "// Generated by gen/fmt_tables.c; do not edit.\n#ifndef FMT_TABLES_H\n#define FMT_TABLES_H\n#include <stdint.h>\n\n"
             "#define FMT_ROOM_MAX %d\nstatic const uint16_t FMT_P2[FMT_ROOM_MAX + 1] = {\n",
          u[0], u[1], u[2], u[3], u[2], u[3], u[1], u[2], u[3], RMAX);
  rows(f, P2, RMAX + 1, 16);
  fputs("};\nstatic const uint32_t FMT_P3[FMT_ROOM_MAX + 1] = {\n", f);
  rows(f, P3, RMAX + 1, 12);
  fprintf(f, "};\nstatic const uint32_t FMT_BEFORE[%d] = {\n", VMAX + 1);
  rows(f, BEFORE, VMAX + 1, 10);
  fputs("};\n\n#endif\n", f);
  if (fclose(f) != 0 || rename("src/fmt_tables.h.part", "src/fmt_tables.h") != 0) { perror("src/fmt_tables.h"); return 1; }
  printf("src/fmt_tables.h: rooms 0 to %d, %ld layouts\n", RMAX, BEFORE[VMAX]);
  return 0;
}
