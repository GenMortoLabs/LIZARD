// Writes ../src/fmt_tables.h: the tables the format word's index takes its layouts by (src/fmt.c ob_fmt_index,
// ob_fmt_config). Every block size is a whole number of OB_FMT_UNIT (640) data slots: the 6/7 code's 7, the 3/4's 8, the
// 2/3's 9 and the 1/2's 12, so a layout of a 6/7, b 3/4, t 2/3 and c 1/2 blocks fits version v when
// 7a + 8b + 9t + 12c <= R(v) = floor(10176 v / 640), at most 1065 (version 67). P2[r] is the number of (t, c) with
// 9t + 12c <= r, P3[r] the number of (b, t, c) with 8b + 9t + 12c <= r, BEFORE[v - 1] the layouts of every version
// before v (sum over a of P3[R - 7a]), the last OB_FMT_CONFIGS.
// Run from the root: node liblizard/gen/fmt_tables.mjs
import { writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";

const SLOTS = 10176, UNIT = 640, VMAX = 67, R = (v) => Math.floor((SLOTS * v) / UNIT), RMAX = R(VMAX);
const P2 = Array.from({ length: RMAX + 1 }, (_, r) => { let n = 0; for (let t = 0; 9 * t <= r; t++) n += Math.floor((r - 9 * t) / 12) + 1; return n; });
const P3 = Array.from({ length: RMAX + 1 }, (_, r) => { let n = 0; for (let b = 0; 8 * b <= r; b++) n += P2[r - 8 * b]; return n; });
const BEFORE = [0];
for (let v = 1; v <= VMAX; v++) { let n = 0; for (let a = 0; 7 * a <= R(v); a++) n += P3[R(v) - 7 * a]; BEFORE.push(BEFORE.at(-1) + n); }
if (BEFORE.at(-1) !== 134069046) throw new Error(`the layouts' count ${BEFORE.at(-1)}`);
if (Math.max(...P2) > 65535) throw new Error("P2 past 16 bits");
const rows = (a, per) => Array.from({ length: Math.ceil(a.length / per) }, (_, i) => `  ${a.slice(per * i, per * i + per).join(", ")},`).join("\n");
const out = `// The format word's layout tables (fmt.c ob_fmt_index, ob_fmt_config): in units of OB_FMT_UNIT (640) data slots, the
// 6/7, 3/4, 2/3 and 1/2 blocks 7, 8, 9 and 12 units. FMT_P2[r]: the (t, c) with 9t + 12c <= r; FMT_P3[r]: the (b, t, c)
// with 8b + 9t + 12c <= r; FMT_BEFORE[v - 1]: the layouts of every version before v, the last OB_FMT_CONFIGS.
// Generated by gen/fmt_tables.mjs; do not edit.
#ifndef FMT_TABLES_H
#define FMT_TABLES_H
#include <stdint.h>

#define FMT_ROOM_MAX ${RMAX}
static const uint16_t FMT_P2[FMT_ROOM_MAX + 1] = {
${rows(P2, 16)}
};
static const uint32_t FMT_P3[FMT_ROOM_MAX + 1] = {
${rows(P3, 12)}
};
static const uint32_t FMT_BEFORE[${VMAX + 1}] = {
${rows(BEFORE, 10)}
};

#endif
`;
writeFileSync(fileURLToPath(new URL("../src/fmt_tables.h", import.meta.url)), out);
console.log(`src/fmt_tables.h: rooms 0 to ${RMAX}, ${BEFORE.at(-1)} layouts`);
