// Writes src/ldpc_stop.h: the LDPC's learned stop for the C decoder, one net a code, from the stop files
// gpu/back/stop/stop60_{67,34,23,12}.safetensors (ldpc-stop-mlp-v2, read after iterations 1 to 59 of a cap of 60).
// Each file is folded by gpu/back/stop/rule.mjs readStop, the same form the GPU kernel runs: the inputs' standardisation,
// 1 / m, the fall (prev - bad) and the growth's 1 / 256 folded into the first layer in float64 and rounded to float32
// once, the threshold T the file's theta less the output bias. The weights are written input-major (W1t[k H + j],
// W2t[k H + j]), so a vector of hidden units reads one row a step.
//   node liblizard/gen/ldpc_stop.mjs        (from the root)
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { readStop } from "../gpu/back/stop/rule.mjs";

const HERE = dirname(fileURLToPath(import.meta.url));
const FILES = [["stop60_67", 640], ["stop60_34", 1280], ["stop60_23", 1920], ["stop60_12", 3840]];
const f32 = (xs) => Array.from(xs, (x) => (Object.is(x, -0) ? "-0.0f" : `${Math.fround(x).toPrecision(9)}f`)).join(", ");
let H = 0;
const out = [
  "// Generated by gen/ldpc_stop.mjs from gpu/back/stop/stop60_*.safetensors: never edited.",
  "// The LDPC's learned stop, one net a code by its checks m, in the folded form of gpu/back/stop/rule.mjs readStop:",
  "// inputs (bad, low, first, prev, t, grow), two hidden ReLU layers, a give-up where the score is under T.",
  "#ifndef LDPC_STOP_TABLES_H",
  "#define LDPC_STOP_TABLES_H",
];
for (const [name, m] of FILES) {
  const r = readStop(new Uint8Array(readFileSync(join(HERE, "..", "gpu", "back", "stop", `${name}.safetensors`))));
  if (r.m !== m) throw new Error(`${name}: m ${r.m}, not ${m}`);
  if (H && r.hidden !== H) throw new Error("every code's net the same width");
  H = r.hidden;
  const W1t = new Float32Array(6 * H), W2t = new Float32Array(H * H);
  for (let j = 0; j < H; j++) for (let k = 0; k < 6; k++) W1t[k * H + j] = r.W1[6 * j + k];
  for (let j = 0; j < H; j++) for (let k = 0; k < H; k++) W2t[k * H + j] = r.W2[H * j + k];
  out.push(`static const float LDPC_STOP_W1_${m}[${6 * H}] = { ${f32(W1t)} };`, `static const float LDPC_STOP_B1_${m}[${H}] = { ${f32(r.b1)} };`,
    `static const float LDPC_STOP_W2_${m}[${H * H}] = { ${f32(W2t)} };`, `static const float LDPC_STOP_B2_${m}[${H}] = { ${f32(r.b2)} };`,
    `static const float LDPC_STOP_W3_${m}[${H}] = { ${f32(r.w3)} };`, `#define LDPC_STOP_T_${m} ${Math.fround(r.T).toPrecision(9)}f   // ${r.code}`);
}
out.push(`enum { LDPC_STOP_H = ${H} };`,
  "typedef struct { int m; const float *W1t, *b1, *W2t, *b2, *w3; float T; } ldpc_stop_t;",
  "static const ldpc_stop_t LDPC_STOPS[4] = {",
  FILES.map(([, m]) => `  { ${m}, LDPC_STOP_W1_${m}, LDPC_STOP_B1_${m}, LDPC_STOP_W2_${m}, LDPC_STOP_B2_${m}, LDPC_STOP_W3_${m}, LDPC_STOP_T_${m} }`).join(",\n"),
  "};", "#endif", "");
writeFileSync(join(HERE, "..", "src", "ldpc_stop.h"), out.join("\n"));
console.log(`wrote src/ldpc_stop.h: ${FILES.length} nets, ${H} hidden units`);
