// ai: Writes src/ldpc_stop.h, the C decoder's learned LDPC stop (src/ldpc.c ldpc_decode_stop): one net a code, from the
// ai: stop files gpu/back/stop/stop60_{67,34,23,12}.safetensors (ldpc-stop-mlp-v2, read after iterations 1 to 59 of a
// ai: cap of 60), each folded by dec/build.cpp readStop, the fold the GPU's stops take (build.h Stop). The weights are
// ai: written input-major (W1t[k H + j], W2t[k H + j]), so a vector of hidden units reads one row a step; every float
// ai: as JavaScript's toPrecision(9) writes it (build.h precision9), so the header is the one the JS generator wrote.
//
//   lizard_ldpc_stop [lib]      lib: liblizard/ (by default); the header written whole, then renamed over the old
#include "build.h"

#include <cmath>
#include <cstdio>
#include <filesystem>
#include <fstream>
#include <iterator>
#include <string>
#include <system_error>
#include <vector>

namespace {

namespace fs = std::filesystem;

std::vector<uint8_t> slurp(const fs::path& p) {
  std::ifstream f(p, std::ios::binary);
  if (!f) throw std::runtime_error("cannot read " + p.string());
  return std::vector<uint8_t>(std::istreambuf_iterator<char>(f), std::istreambuf_iterator<char>());
}

// ai: a float32 as a C literal: toPrecision(9)'s digits and an f; a negative zero -0.0f
std::string f32(float x) { return x == 0 && std::signbit(x) ? "-0.0f" : lizard::build::precision9(x) + "f"; }
std::string list(const std::vector<float>& v) {
  std::string s;
  for (size_t i = 0; i < v.size(); i++) s += (i ? ", " : "") + f32(v[i]);
  return s;
}

}  // namespace

int main(int argc, char** argv) {
  const fs::path lib = argc > 1 ? fs::u8path(argv[1]) : fs::path("liblizard");
  // ai: each code's file by its checks: 6/7 640, 3/4 1280, 2/3 1920, 1/2 3840
  const std::pair<const char*, int> FILES[] = {{"stop60_67", 640}, {"stop60_34", 1280}, {"stop60_23", 1920}, {"stop60_12", 3840}};
  try {
    std::string out =
        "// Generated by core/tools/ldpc_stop.cpp from gpu/back/stop/stop60_*.safetensors: never edited.\n"
        "// The LDPC's learned stop, one net a code by its checks m, in the folded form of core/dec/build.cpp readStop:\n"
        "// inputs (bad, low, first, prev, t, grow), two hidden ReLU layers, a give-up where the score is under T.\n"
        "#ifndef LDPC_STOP_TABLES_H\n#define LDPC_STOP_TABLES_H\n";
    int H = 0;
    for (const auto& [name, m] : FILES) {
      const std::string path = std::string("gpu/back/stop/") + name + ".safetensors";
      const lizard::build::Stop r = lizard::build::readStop(slurp(lib / path), path);
      if (r.m != m) throw std::runtime_error(std::string(name) + ": m " + std::to_string(r.m) + ", not " + std::to_string(m));
      if (H && r.hidden != H) throw std::runtime_error("every code's net the same width");
      H = r.hidden;
      const size_t h = static_cast<size_t>(H);
      std::vector<float> W1t(6 * h), W2t(h * h);
      for (size_t j = 0; j < h; j++) for (size_t k = 0; k < 6; k++) W1t[k * h + j] = r.W1[6 * j + k];
      for (size_t j = 0; j < h; j++) for (size_t k = 0; k < h; k++) W2t[k * h + j] = r.W2[h * j + k];
      const std::string M = std::to_string(m);
      out += "static const float LDPC_STOP_W1_" + M + "[" + std::to_string(6 * h) + "] = { " + list(W1t) + " };\n";
      out += "static const float LDPC_STOP_B1_" + M + "[" + std::to_string(h) + "] = { " + list(r.b1) + " };\n";
      out += "static const float LDPC_STOP_W2_" + M + "[" + std::to_string(h * h) + "] = { " + list(W2t) + " };\n";
      out += "static const float LDPC_STOP_B2_" + M + "[" + std::to_string(h) + "] = { " + list(r.b2) + " };\n";
      out += "static const float LDPC_STOP_W3_" + M + "[" + std::to_string(h) + "] = { " + list(r.w3) + " };\n";
      out += "#define LDPC_STOP_T_" + M + " " + lizard::build::precision9(r.T) + "f   // " + r.code + "\n";
    }
    out += "enum { LDPC_STOP_H = " + std::to_string(H) + " };\n";
    out += "typedef struct { int m; const float *W1t, *b1, *W2t, *b2, *w3; float T; } ldpc_stop_t;\n";
    out += "static const ldpc_stop_t LDPC_STOPS[4] = {\n";
    for (size_t i = 0; i < std::size(FILES); i++) {
      const std::string M = std::to_string(FILES[i].second);
      out += "  { " + M + ", LDPC_STOP_W1_" + M + ", LDPC_STOP_B1_" + M + ", LDPC_STOP_W2_" + M + ", LDPC_STOP_B2_" + M + ", LDPC_STOP_W3_" + M + ", LDPC_STOP_T_" + M + " }" +
             (i + 1 < std::size(FILES) ? ",\n" : "\n");
    }
    out += "};\n#endif\n";
    const fs::path at = lib / "src" / "ldpc_stop.h", tmp = lib / "src" / "ldpc_stop.h.part";
    {
      std::ofstream f(tmp, std::ios::binary);
      if (!(f << out) || !f.flush()) throw std::runtime_error("cannot write " + tmp.string());
    }
    fs::rename(tmp, at);
    printf("wrote %s: %zu nets, %d hidden units\n", at.string().c_str(), std::size(FILES), H);
    return 0;
  } catch (const std::exception& e) {
    fprintf(stderr, "lizard_ldpc_stop: %s\n", e.what());
    return 1;
  }
}
